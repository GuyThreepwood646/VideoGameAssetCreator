"""Write CREDITS.md at the repository root from the same data the Credits page shows (backend/vgac/credits.py).

Run: backend/.venv/Scripts/python.exe tools/make_credits.py
"""
from __future__ import annotations

import importlib.metadata as md
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))

from vgac.credits import credits  # noqa: E402


def render() -> str:
    ans = credits()
    s = ans["summary"]
    out = ["# Credits", "", "Video Game Asset Creator is built on the work below. " + s["not_legal_advice"], ""]
    for key in ("passing_on", "before_sharing", "game_credit"):
        out += ["## " + s[key]["title"], ""] + ["- " + p for p in s[key]["points"]] + [""]
    for g in ans["groups"]:
        out += ["## " + g["title"], "", g["intro"], ""]
        out += ["| Name | What it does here | Author | Licence | Credit required | In your assets |", "|---|---|---|---|---|---|"]
        for e in g["entries"]:
            name = f"[{e['name']}]({e['link']})" if e["link"] else e["name"]
            lic = e["licence"] + (" (" + e["note"] + ")" if e["note"] else "")
            row = [name, e["does"], e["author"], lic, "yes" if e["attribution_required"] else "no", "yes" if e["in_your_assets"] else "no"]
            out.append("| " + " | ".join(c.replace("|", "/") for c in row) + " |")
        out.append("")
    out += ["Generated by tools/make_credits.py from backend/vgac/data/credits.yaml, models.yaml, addons.yaml and the hair library catalogue. Do not edit by hand.", ""]
    return "\n".join(out)


def _canon(n: str) -> str:
    return re.sub(r"[-_.]+", "-", n).lower()


def _licence(d: md.Distribution) -> str:
    m = d.metadata
    lic = m.get("License-Expression") or ""
    if not lic:
        raw = (m.get("License") or "").strip()
        if raw and len(raw) < 60 and "\n" not in raw:
            lic = raw
    if not lic:
        cl = [c.split("::")[-1].strip() for c in (m.get_all("Classifier") or []) if c.startswith("License ::")]
        lic = "; ".join(x for x in cl if x != "OSI Approved") or "not stated in the package"
    return lic.replace("|", "/")


def python_packages() -> tuple[list[tuple[str, str, str]], list[tuple[str, str, str]]]:
    """(shipped, test_only) from the installed metadata in backend/.venv: the dependency closure of requirements.txt
    without pytest is shipped; what only pytest pulls in is test-only."""
    dists = {_canon(d.metadata["Name"]): d for d in md.distributions()}

    def closure(roots: list[str]) -> set[str]:
        seen: set[str] = set()
        todo = [_canon(r) for r in roots]
        while todo:
            n = todo.pop()
            if n in seen or n not in dists:
                continue
            seen.add(n)
            for r in dists[n].requires or []:
                if "extra ==" in r:
                    continue
                todo.append(_canon(re.split(r"[ ;<>=!~\[(]", r.strip(), maxsplit=1)[0]))
        return seen

    roots = []
    for line in (ROOT / "backend" / "requirements.txt").read_text(encoding="utf-8").splitlines():
        line = line.split("#")[0].strip()
        if line:
            roots.append(re.split(r"[<>=!~\[ ]", line, maxsplit=1)[0])
    shipped = closure([r for r in roots if _canon(r) != "pytest"])
    # uvicorn[standard] pulls these in through an extra
    shipped |= closure(["httptools", "watchfiles", "uvloop", "python-dotenv", "colorama", "pyyaml", "websockets"])
    test = closure(["pytest"]) - shipped

    def row(n: str) -> tuple[str, str, str]:
        return (dists[n].metadata["Name"], dists[n].version, _licence(dists[n]))

    return sorted(map(row, shipped), key=lambda r: r[0].lower()), sorted(map(row, test), key=lambda r: r[0].lower())


def js_packages(folder: str) -> tuple[list[tuple[str, str, str]], list[tuple[str, str, str]]]:
    """(shipped, build_only) from package-lock.json: entries not marked dev are shipped; type-only packages are build-only."""
    pk = json.loads((ROOT / folder / "package-lock.json").read_text(encoding="utf-8"))["packages"]
    shipped, build = [], []
    for key, v in pk.items():
        if not key:
            continue
        name = key.split("node_modules/")[-1]
        lic = v.get("license") or "not stated in the lock file"
        lic = lic if isinstance(lic, str) else json.dumps(lic)
        row = (name, v.get("version", ""), lic.replace("|", "/"))
        (build if v.get("dev") or v.get("devOptional") or name.startswith("@types/") else shipped).append(row)
    return sorted(shipped), sorted(build)


def _table(rows: list[tuple[str, str, str]]) -> list[str]:
    return ["| Package | Version | Licence |", "|---|---|---|"] + [f"| {n} | {v} | {lic} |" for n, v, lic in rows] + [""]


def render_notices() -> str:
    py, py_test = python_packages()
    fe, fe_build = js_packages("frontend")
    _dk, dk_build = js_packages("desktop")
    out = ["# Third-party notices", "",
           "Every package that ships with Video Game Asset Creator, with its licence, read from the installed Python packages in backend/.venv "
           "and from the lock files of frontend/ and desktop/. Names and licence identifiers only; each package carries its own full licence text "
           "(in its folder or on its project page). Keep this file with the app when you share it. This is information, not legal advice.", "",
           "## Python packages (backend)", ""] + _table(py)
    out += ["## JavaScript packages in the frontend build", ""] + _table(fe)
    out += ["## Desktop launcher", "",
            "The launcher packs Electron, which ships Chromium and Node.js; Electron's own licence files (LICENSE and LICENSES.chromium.html) "
            "travel inside every build it makes. Electron is MIT. Nothing else in desktop/ is shipped.", "",
            "## Used to build or test, not shipped", "", "Python (tests only)", ""] + _table(py_test)
    out += ["Frontend build tools and type definitions", ""] + _table(fe_build)
    out += [f"Desktop build tools (electron-builder and what it pulls in): {len(dk_build)} packages, listed in desktop/package-lock.json.", "",
            "Generated by tools/make_credits.py. Do not edit by hand.", ""]
    return "\n".join(out)


if __name__ == "__main__":
    (ROOT / "CREDITS.md").write_text(render(), encoding="utf-8", newline="\n")
    (ROOT / "THIRD-PARTY-NOTICES.md").write_text(render_notices(), encoding="utf-8", newline="\n")
    print("wrote CREDITS.md and THIRD-PARTY-NOTICES.md in", ROOT)
