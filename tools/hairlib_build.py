"""Build the hair library (backend/vgac/data/hairlib) from the CC0 hair packs. Offline; run by hand with the backend venv.

    backend/.venv/Scripts/python.exe -I tools/hairlib_build.py --packs F:/Projects/VideoGameAssetCreator/runtime/hairpacks
        [--out backend/vgac/data/hairlib] [--only id ...] [--tex 1024] [--normal 512] [--no-cap-check] [--blender <blender.exe>]

Packs that are not there are skipped (their styles are left out and the catalogue lists only what was built), so the
library can be built from whichever of the three packs the person has. setup/Setup-Extras.ps1 -Packs runs this into
library/hairlib. Blender: --blender, else the VGAC_BLENDER environment variable, else the default below.

Reads the packs read-only as data (OBJ, glTF and their JSON, PNG, .mhclo/.mhmat text); runs no script from a pack.
Steps: read curation.yaml; check each pack style's licence in its own file (MakeHuman .mhclo header; the Quaternius
pack's licence file) and refuse anything that is not CC0; make the shared textures (grey LA PNG at --tex with the
median hair luminance at 0.5 and alpha kept for cards; normal map at --normal for shells; named by the first 8 hex of
their content's sha1, stored once); run tools/hairlib_blender.py in Blender for the meshes, hanging groups, lite
variants and thumbnails; write catalogue.json (docs/HAIR-LIBRARY-PLAN.md section 4) and CREDITS.txt (kept styles
and the "Left out" list with the licence line found); enforce the 40 MB cap."""
import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

import numpy as np
import yaml
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
BLENDER = os.environ.get("VGAC_BLENDER", r"F:/Tools/blender-5.2.3-windows-x64/blender.exe")
CAP_BYTES = 40 * 1024 * 1024
Image.MAX_IMAGE_PIXELS = None

QB = ("quaternius_ubc", "unpacked", "Universal Base Characters[Standard]")
PACK_DIRS = {
    "quaternius": QB + ("Hairstyles", "Origin at 0", "glTF (Godot)"),
    "mh_hair01": ("makehuman_hair01", "unpacked", "hair"),
    "mh_system": ("makehuman_system", "unpacked", "hair"),
}
REFS = {
    "q_female": QB + ("Base Characters", "Godot - UE", "Superhero_Female_FullBody.gltf"),
    "q_male": QB + ("Base Characters", "Godot - UE", "Superhero_Male_FullBody.gltf"),
    "mh_female": ("makehuman_system", "unpacked", "proxymeshes", "female_generic", "female_generic.obj"),
    "mh_male": ("makehuman_system", "unpacked", "proxymeshes", "male_generic", "male_generic.obj"),
}
SOURCES = {
    "quaternius": dict(url="https://quaternius.com", author="Quaternius", pack="Universal Base Characters (Standard)"),
    "mh_hair01": dict(url="http://www.makehumancommunity.org", author=None, pack="MakeHuman community hair pack hair01"),
    "mh_system": dict(url="http://www.makehumancommunity.org", author="MakeHuman team (Data Collection AB)", pack="MakeHuman system assets"),
    "rule": dict(url="", author="VGAC (generated by rule)", pack="VGAC rule-built styles"),
}


def pack_path(packs: Path, parts) -> Path:
    return packs.joinpath(*parts)


def pack_present(packs: Path, pack: str) -> bool:
    """The rule-built styles need no pack; a pack is there when its hair folder (or the Quaternius hair folder) is."""
    return pack == "rule" or pack_path(packs, PACK_DIRS[pack]).is_dir()


def licence_of(packs: Path, pack: str, src: str) -> tuple[bool, str, str | None]:
    """(is CC0, the licence line found, author)."""
    if pack == "rule":
        return True, "generated by VGAC, CC0", "VGAC"
    if pack == "quaternius":
        lic = pack_path(packs, QB + ("License_Standard.txt",)).read_text(encoding="utf-8", errors="replace")
        m = re.search(r"CC0 1\.0 Universal[^\n]*", lic)
        return bool(m), (m.group(0).strip() if m else "no CC0 line"), "Quaternius"
    d = pack_path(packs, PACK_DIRS[pack]) / src
    clo = next(iter(sorted(d.glob("*.mhclo"))), None)
    if clo is None:
        return False, "no .mhclo file", None
    head = [l.strip() for l in clo.read_text(encoding="utf-8", errors="replace").splitlines()[:20] if l.startswith("#")]
    author = None
    for l in head:
        m = re.match(r"#\s*author\s+(.+)", l, re.I)
        if m:
            author = m.group(1).strip()
    lic_lines = [l for l in head if re.search(r"licen[cs]e|CC0|CC-0|released as", l, re.I)]
    line = " / ".join(lic_lines) if lic_lines else "no licence line"
    text = " ".join(lic_lines)
    ok = bool(re.search(r"CC0|CC-0", text)) and not re.search(r"AGPL|GPL|CC[ _-]?BY", text, re.I)
    return ok, line, author


def mh_files(d: Path) -> dict:
    clo = next(iter(sorted(d.glob("*.mhclo"))))
    txt = clo.read_text(encoding="utf-8", errors="replace")
    obj = re.search(r"^obj_file\s+(\S+)", txt, re.M).group(1)
    mat = re.search(r"^material\s+(\S+)", txt, re.M)
    matf = d / mat.group(1) if mat and (d / mat.group(1)).exists() else next(iter(sorted(d.glob("*.mhmat"))), None)
    mm = {}
    if matf:
        for line in matf.read_text(encoding="utf-8", errors="replace").splitlines():
            line = line.strip()
            if line and not line.startswith(("#", "//")):
                k, _, v = line.partition(" ")
                mm[k] = v.strip()
    return dict(obj=d / obj, base=d / mm["diffuseTexture"] if "diffuseTexture" in mm else None,
                normal=d / mm["normalmapTexture"] if "normalmapTexture" in mm else None)


def gltf_files(p: Path) -> dict:
    g = json.loads(p.read_text(encoding="utf-8"))
    base = normal = None
    for m in g.get("materials", []):
        pbr = m.get("pbrMetallicRoughness", {})
        if "baseColorTexture" in pbr and base is None:
            base = p.parent / g["images"][g["textures"][pbr["baseColorTexture"]["index"]]["source"]]["uri"]
        if "normalTexture" in m and normal is None:
            normal = p.parent / g["images"][g["textures"][m["normalTexture"]["index"]]["source"]]["uri"]
    return dict(obj=p, base=base, normal=normal)


def sha8(b: bytes) -> str:
    return hashlib.sha1(b).hexdigest()[:8]


def grey_texture(src: Path, size: int, cards: bool) -> Image.Image:
    im = Image.open(src)
    has_a = im.mode in ("RGBA", "LA", "PA") or (im.mode == "P" and "transparency" in im.info)
    im = im.convert("RGBA").resize((size, size), Image.LANCZOS)
    a = np.asarray(im).astype(float)
    c = a[..., :3] / 255.0
    lin = np.where(c > 0.04045, ((c + 0.055) / 1.055) ** 2.4, c / 12.92)
    L = lin @ np.array([0.2126, 0.7152, 0.0722])
    alpha = a[..., 3] if (has_a and cards) else np.full(L.shape, 255.0)
    m = alpha > 127
    med = float(np.median(L[m])) if m.any() else float(L.mean())
    g = np.clip(L * (0.5 / max(med, 1e-4)), 0, 1)
    if cards and (~m).any():
        # bleed the hair's values into the see-through texels: the packs leave white or noise there, which shows as a
        # light band at cut edges (blunt fringes) once mipmaps or the 0.5 cutout pick up partly transparent texels
        from PIL import ImageFilter
        fill = g * m
        w = m.astype(float)
        for r in (2, 6, 16, 40):
            num = np.asarray(Image.fromarray((fill * 255).astype(np.uint8)).filter(ImageFilter.BoxBlur(r))).astype(float) / 255
            den = np.asarray(Image.fromarray((w * 255).astype(np.uint8)).filter(ImageFilter.BoxBlur(r))).astype(float) / 255
            est = np.where(den > 1e-3, num / np.maximum(den, 1e-3), 0.5)
            g = np.where(m, g, np.where(den > 1e-3, est, g))
            fill = np.where(m, fill, est * (den > 1e-3))
            w = np.maximum(w, (den > 1e-3).astype(float))
        g = np.where(m, g, np.minimum(g, 0.5))     # never lighter than the median at the cut edge
    out = np.dstack([(g * 255).round(), alpha]).astype(np.uint8)
    return Image.fromarray(out, "LA")


def save_unique(img: Image.Image, tex_dir: Path, suffix: str) -> str:
    import io
    buf = io.BytesIO(); img.save(buf, "PNG", optimize=True)
    data = buf.getvalue()
    name = f"{sha8(data)}_{suffix}.png"
    p = tex_dir / name
    if not p.exists():
        p.write_bytes(data)
    return name


def file_sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--packs", required=True)
    ap.add_argument("--out", default=str(ROOT / "backend" / "vgac" / "data" / "hairlib"))
    ap.add_argument("--curation", default=None)
    ap.add_argument("--only", nargs="*", default=None)
    ap.add_argument("--tex", type=int, default=1024)
    ap.add_argument("--normal", type=int, default=512)
    ap.add_argument("--scratch", default=str(ROOT / "runtime" / "tmp" / "hairlib" / "build"))
    ap.add_argument("--no-cap-check", action="store_true")
    ap.add_argument("--blender", default=None)
    a = ap.parse_args()
    blender = a.blender or BLENDER
    packs, out = Path(a.packs).resolve(), Path(a.out).resolve()
    cur = yaml.safe_load(open(a.curation or (ROOT / "backend" / "vgac" / "data" / "hairlib" / "curation.yaml"), encoding="utf-8"))
    out.mkdir(parents=True, exist_ok=True)
    if a.curation is None and out != ROOT / "backend" / "vgac" / "data" / "hairlib":
        shutil.copy2(ROOT / "backend" / "vgac" / "data" / "hairlib" / "curation.yaml", out / "curation.yaml")
    elif a.curation and Path(a.curation).resolve() != (out / "curation.yaml").resolve():
        shutil.copy2(a.curation, out / "curation.yaml")
    for sub in ("styles", "tex", "thumbs"):
        (out / sub).mkdir(exist_ok=True)
    tex_dir = out / "tex"
    hair01_meta = {}
    hp = packs / "makehuman_hair01" / "unpacked" / "packs" / "hair01.json"
    if hp.exists():
        hair01_meta = json.loads(hp.read_text(encoding="utf-8"))
    kept, refused, job_styles = {}, [], []
    # every MakeHuman style in the packs is checked so the "Left out" list is complete
    for pack in ("mh_hair01", "mh_system"):
        if not pack_present(packs, pack):
            continue
        for d in sorted(pack_path(packs, PACK_DIRS[pack]).iterdir()):
            if d.is_dir():
                ok, line, _ = licence_of(packs, pack, d.name)
                if not ok:
                    refused.append(dict(style=f"{pack}:{d.name}", licence_line=line))
    for sid, c in cur["styles"].items():
        if a.only and sid not in a.only:
            continue
        needs = [c["pack"]] + ([cur["styles"][c["texture_from"]]["pack"]] if c.get("texture_from") else [])
        # every style is fitted on a reference head that comes from a pack (the MakeHuman proxies or the Quaternius figures)
        if not all(pack_present(packs, n) for n in needs) or not pack_path(packs, REFS[c["ref"]]).is_file():
            print("SKIPPED (pack not present)", sid)
            continue
        ok, line, author = licence_of(packs, c["pack"], c["src"])
        if not ok:
            print("REFUSED", sid, line)
            continue
        if c["pack"] == "rule":
            files = dict(obj=None, base=None, normal=None)
        elif c["pack"] == "quaternius":
            files = gltf_files(pack_path(packs, PACK_DIRS["quaternius"]) / c["src"])
        else:
            files = mh_files(pack_path(packs, PACK_DIRS[c["pack"]]) / c["src"])
        if c.get("texture_from"):
            # several colour versions of one atlas (the toigo bobs): every one uses the named style's texture
            src_c = cur["styles"][c["texture_from"]]
            files["base"] = mh_files(pack_path(packs, PACK_DIRS[src_c["pack"]]) / src_c["src"])["base"]
        cards = c["kind"] == "cards"
        grey = normal = None
        if files["base"]:
            grey = save_unique(grey_texture(files["base"], a.tex, cards), tex_dir, "grey")
        if files["normal"] and not cards:
            nimg = Image.open(files["normal"]).convert("RGB").resize((a.normal, a.normal), Image.LANCZOS)
            normal = save_unique(nimg, tex_dir, "normal")
        if c["pack"] == "mh_hair01":
            author = (hair01_meta.get(c["src"], {}).get("author") or author)
        src = SOURCES[c["pack"]]
        kept[sid] = dict(c=c, line=line, author=author or src["author"], grey=grey, normal=normal, src_files={k: str(v) if v else None for k, v in files.items()})
        job_styles.append(dict(id=sid, rule=c["pack"] == "rule", path=str(files["obj"]) if files["obj"] else None, ref=c["ref"],
                               grey=str(tex_dir / grey) if grey else None, normal=str(tex_dir / normal) if normal else None,
                               kind=c["kind"], alpha="cutout" if cards else "opaque", thin=c.get("thin"), hang_groups=c.get("hang_groups")))
    scratch = Path(a.scratch); scratch.mkdir(parents=True, exist_ok=True)
    if not job_styles:
        print("NOTHING TO BUILD: none of the packs is in", packs)
        return 3
    used_refs = {s_["ref"] for s_ in job_styles}
    job = dict(out=str(out), refs={k: str(pack_path(packs, v)) for k, v in REFS.items() if k in used_refs}, styles=job_styles, tex=a.tex)
    jp = scratch / "build_job.json"
    jp.write_text(json.dumps(job, indent=1), encoding="utf-8")
    log = scratch / "build_blender.log"
    with open(log, "w", encoding="utf-8") as lf:
        r = subprocess.run([blender, "-b", "--python", str(ROOT / "tools" / "hairlib_blender.py"), "--", str(jp)], stdout=lf, stderr=subprocess.STDOUT)
    meas = json.loads((out / "build_measures.json").read_text(encoding="utf-8"))
    missing = [s for s in kept if s not in meas]
    if r.returncode or missing:
        print("BLENDER FAILED or missing:", missing, "see", log)
        return 1
    # rule-built grey textures come back as RGBA from Blender
    for sid, k in kept.items():
        if k["c"]["pack"] == "rule":
            p = tex_dir / f"{sid}_rule_grey.png"
            g = Image.open(p).convert("L")
            k["grey"] = save_unique(Image.merge("LA", (g, Image.new("L", g.size, 255))), tex_dir, "grey")
            p.unlink()
    cat_path = out / "catalogue.json"
    catalogue = json.loads(cat_path.read_text(encoding="utf-8")) if (cat_path.exists() and a.only) else {"styles": {}}
    for sid, k in kept.items():
        c, m = k["c"], meas[sid]
        cards = c["kind"] == "cards"
        # display name from curation; the pack's own name is kept as pack_name (and in the credit)
        if c["pack"] == "rule":
            import importlib.util
            spec = importlib.util.spec_from_file_location("rb", ROOT / "tools" / "hairlib_rulebuilt.py")
            rb = importlib.util.module_from_spec(spec); spec.loader.exec_module(rb)
            pack_name = rb.RULE_STYLES[sid]["name"]
        elif c["pack"] == "quaternius":
            pack_name = Path(c["src"]).stem
        else:
            clo = next(iter(sorted((pack_path(packs, PACK_DIRS[c["pack"]]) / c["src"]).glob("*.mhclo"))))
            mm = re.search(r"^name\s+(.+)$", clo.read_text(encoding="utf-8", errors="replace"), re.M)
            pack_name = mm.group(1).strip() if mm else c["src"]
        name = c.get("name") or pack_name
        files = {"npz": f"styles/{sid}.npz"}
        if m.get("lite_triangles"):
            files["lite"] = f"styles/{sid}_lite.npz"
        files["thumb_front"] = f"thumbs/{sid}_front.png"; files["thumb_quarter"] = f"thumbs/{sid}_quarter.png"
        files["grey"] = f"tex/{k['grey']}"
        if k["normal"]:
            files["normal"] = f"tex/{k['normal']}"
        lite_ok = bool(m.get("lite_triangles") and m["lite_triangles"] <= 750)
        catalogue["styles"][sid] = dict(
            id=sid, name=name, pack_name=pack_name, pack=SOURCES[c["pack"]]["pack"], source_url=SOURCES[c["pack"]]["url"], author=k["author"],
            licence="CC0-1.0", licence_line=k["line"], source_file=k["src_files"].get("obj"),
            family=c["family"], fringe=bool(c["fringe"]), curly=bool(c.get("curly", False)), parting=c["parting"], length_rel_head=m["length_rel_head"],
            kind=c["kind"], alpha="cutout" if cards else "opaque", two_sided=bool(cards or c.get("two_sided", False)),
            triangles=m["triangles"], source_triangles=m["source_triangles"], vertices=m["vertices"],
            hang_groups=[{kk: g[kk] for kk in ("k", "kind", "path_q", "length_q")} for g in m["hang_groups"]][:3],
            textures=dict(grey=files["grey"], normal=files.get("normal"), size=a.tex),
            phone_ok=(not cards) and lite_ok, lite=files.get("lite"), lite_triangles=m.get("lite_triangles"),
            default_params=dict(volume=1.0, dz_head=0.0, length=1.0, mirror=False),
            thumbs=dict(front=files["thumb_front"], quarter=files["thumb_quarter"]),
            self_check_mm=m["self_check_mm"], notes=c.get("notes", ""),
            sha256={k2: file_sha256(out / v) for k2, v in files.items()})
    catalogue["version"] = 1
    catalogue["refused"] = refused
    present = {"quaternius": pack_present(packs, "quaternius"), "mh_system": pack_present(packs, "mh_system"), "mh_hair01": pack_present(packs, "mh_hair01")}
    left_out = {k2: v2 for k2, v2 in (cur.get("left_out") or {}).items() if present.get(k2.split(":")[0], True)}
    catalogue["left_out"] = left_out
    cat_path.write_text(json.dumps(catalogue, indent=1), encoding="utf-8")
    lines = ["Hair library credits (backend/vgac/data/hairlib)", "",
             "Every style below is CC0 1.0 (public domain dedication) by its own file. No attribution is required; it is given anyway.", ""]
    for sid, e in sorted(catalogue["styles"].items()):
        lines.append(f"{sid}: \"{e['pack_name']}\" (shown as \"{e['name']}\") by {e['author']}, from {e['pack']} ({e['source_url'] or 'generated in VGAC'}). Licence line: {e['licence_line']}")
    lines += ["", "Left out", ""]
    for r in refused:
        lines.append(f"{r['style']}: licence line found: {r['licence_line']}")
    for k2, why in left_out.items():
        lines.append(f"{k2}: {why}")
    (out / "CREDITS.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (out / "build_measures.json").unlink(missing_ok=True)
    # unused textures (from earlier builds) go
    used = {Path(e["textures"]["grey"]).name for e in catalogue["styles"].values()} | {Path(e["textures"]["normal"]).name for e in catalogue["styles"].values() if e["textures"]["normal"]}
    for p in tex_dir.glob("*.png"):
        if p.name not in used:
            p.unlink()
    # files of styles that are not in this build (an earlier build had more packs)
    keep = {Path(v).as_posix() for e in catalogue["styles"].values() for v in (e["thumbs"]["front"], e["thumbs"]["quarter"], f"styles/{e['id']}.npz", e.get("lite")) if v}
    for sub in ("styles", "thumbs"):
        for p in (out / sub).glob("*"):
            if p.is_file() and f"{sub}/{p.name}" not in keep:
                p.unlink()
    total = sum(p.stat().st_size for p in out.rglob("*") if p.is_file())
    print(f"styles {len(catalogue['styles'])}, refused {len(refused)}, total {total / 1e6:.1f} MB")
    if total > CAP_BYTES and not a.no_cap_check:
        print("OVER THE 40 MB CAP")
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
