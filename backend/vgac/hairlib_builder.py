"""Build the hair library from the CC0 hair packs (the app's own code; tools/hairlib_build.py is a thin command line over it).

Used by the in-app "Get the hair library" step (vgac/packs.py) and by setup/Setup-Extras.ps1. Offline.

Reads the packs read-only as data (OBJ, glTF and their JSON, PNG, .mhclo/.mhmat text); runs no script from a pack.
Steps: read curation.yaml; check each pack style's licence in its own file (MakeHuman .mhclo header; the Quaternius
pack's licence file) and refuse anything that is not CC0; make the shared textures (grey LA PNG at `tex` with the
median hair luminance at 0.5 and alpha kept for cards; normal map at `normal` for shells; named by the first 8 hex of
their content's sha1, stored once); run blender/hairlib_blender.py in Blender for the meshes, hanging groups, lite
variants and thumbnails; write catalogue.json (docs/HAIR-LIBRARY-PLAN.md section 4) and CREDITS.txt (kept styles
and the "Left out" list with the licence line found); enforce the 40 MB cap.

Packs that are not there are skipped (their styles are left out and the catalogue lists only what was built), so the
library can be built from whichever of the packs the person has. verify() checks a built folder (files present,
checksums, arrays); compare() checks it against another library."""
